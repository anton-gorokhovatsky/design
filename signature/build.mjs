import { readFile, writeFile, mkdir } from 'node:fs/promises';

const base = new URL('./', import.meta.url);
const read = path => readFile(new URL(path, base), 'utf8');
const [source, componentCSS, motionCSS, svg] = await Promise.all([
  read('src/component.js'), read('src/component.css'), read('src/motion.css'), read('src/mark.svg'),
]);
const version = source.match(/export const VERSION = "([\d.]+)";/)?.[1];
if (!version || !svg.includes('viewBox="0 7 64 46"')) throw new Error('Missing version or accepted artwork');

// Only SVG accessibility/presentation attributes change; every drawing atom stays literal.
const mark = svg.replace(' color="#315dff"', '')
  .replace(/\s*<(title|desc)>[\s\S]*?<\/\1>/g, '')
  .replace('<svg ', '<svg class="mark" aria-hidden="true" focusable="false" data-arc-running="false" ');
const bundle = `/* Author signature ${version}. Generated by signature/build.mjs; edit signature/src instead. */\n`
  + source.replace('__SIGNATURE_CSS__', () => JSON.stringify(componentCSS+'\n'+motionCSS))
    .replace('__SIGNATURE_SVG__', () => JSON.stringify(mark));
await mkdir(new URL('v1/', base), { recursive: true });
await writeFile(new URL('v1/signature.js', base), bundle);
console.log(`Built signature v${version}: ${Buffer.byteLength(bundle)} bytes, no runtime dependencies.`);
